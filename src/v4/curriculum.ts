import type { Lesson, Question } from "../data/lessons";
import type { BrowserUnit } from "../browser/curriculum";
export type AdvancedUnit = BrowserUnit & {
  tool:
    | "scope"
    | "context"
    | "closure"
    | "binding"
    | "async"
    | "promise"
    | "http"
    | "dependency"
    | "json"
    | "live";
  related: string;
  use: string;
};
const html =
  '<button id="act">Try the action</button><p id="status" role="status"></p><div id="out"></div>';
function unit(
  chapter: number,
  id: string,
  title: string,
  why: string,
  what: string,
  analogy: string,
  code: string,
  prompt: string,
  choices: string[],
  answer: number,
  explanation: string,
  broken: string,
  hint: string,
  task: string,
  recap: string,
  tool: AdvancedUnit["tool"],
  related: string,
  how: string[],
  expected?: string[],
): AdvancedUnit {
  const q = (
    suffix: string,
    kind: string,
    prompt: string,
    choices: string[],
    answer: number,
    explanation: string,
    code?: string,
  ): Question => ({
    id: "v4-" + id + "-" + suffix,
    kind,
    prompt,
    choices,
    answer,
    explanation,
    code,
  });
  return {
    chapter,
    id: "v4-" + id,
    title,
    why,
    what,
    analogy,
    html,
    code,
    expected,
    questions: [
      q(
        "p",
        "Reason before running",
        prompt,
        choices,
        answer,
        explanation +
          " Use this when " +
          why.toLowerCase() +
          " Revise: " +
          recap,
      ),
      q(
        "fix",
        "Read and repair",
        "Which diagnosis fits this broken example?",
        [
          hint,
          "Repeat execution without inspecting its inputs",
          "Assume visible output proves every branch correct",
        ],
        0,
        hint + " " + recap,
        broken,
      ),
    ],
    broken,
    hint,
    task,
    recap,
    tool,
    related,
    use: task,
    misconception: explanation,
    how,
  };
}
