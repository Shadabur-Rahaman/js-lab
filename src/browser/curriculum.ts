export type BrowserUnit = {
  id: string;
  chapter: number;
  title: string;
  why: string;
  what: string;
  analogy: string;
  how: string[];
  html: string;
  css?: string;
  code: string;
  expected?: string[];
  misconception: string;
  broken: string;
  hint: string;
  task: string;
  recap: string;
  questions: Question[];
};
function question(
  id: string,
  prompt: string,
  choices: string[],
  answer: number,
  explanation: string,
  kind = "Predict the result",
): Question {
  return { id, kind, prompt, choices, answer, explanation };
}
